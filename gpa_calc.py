def calculate_semester_gpa(semester_name, grades):
    """
    Calculate GPA for a specific semester
    
    Args:
        semester_name: Name of the semester (e.g., "Semester 1")
        grades: Dictionary with course codes as keys and grade points as values
                Example: {"CSE-1101": 4.0, "CSE-1102": 3.75, ...}
    
    Returns:
        Calculated GPA (float)
    """
    courses = courses_data[semester_name]
    
    total_grade_points = 0
    total_credits = 0
    
    for course in courses:
        course_code = course["code"]
        credit = course["credit"]
        
        if course_code in grades:
            grade_point = grades[course_code]
            total_grade_points += grade_point * credit
            total_credits += credit
    
    if total_credits == 0:
        return 0.0
    
    gpa = total_grade_points / total_credits
    return round(gpa, 2)


